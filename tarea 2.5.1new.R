# Datos del ejercicio
cd4 <- c(230,205,313,207,227,245,173,
         58,103,181,105,301,169)

print("Datos utilizados:")
print(cd4)

# minimo
minimo <- min(cd4)

# maximo
maximo <- max(cd4)

# rango
rango <- maximo - minimo

print("Valor minimo:")
print(minimo)

print("Valor maximo:")
print(maximo)

print("Rango:")
print(rango)